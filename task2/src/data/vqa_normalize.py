ARTICLES = {"a", "an", "the"}

PERIOD_STRIP = re.compile(r"(?!<=\d)(\.)(?!\d)")
COMMA_STRIP = re.compile(r"(\d)(\,)(\d)")
PUNCT = [
    ";",
    r"/",
    "[",
    "]",
    '"',
    "{",
    "}",
    "(",
    ")",
    "=",
    "+",
    "\\",
    "_",
    "-",
    ">",
    "<",
    "@",
    "`",
    ",",
    "?",
    "!",
]

_THINK_RE = re.compile(r"<think>.*?</think>", flags=re.DOTALL | re.IGNORECASE)


def process_punctuation(in_text: str) -> str:
    out_text = in_text
    for punct in PUNCT:
        if (punct + " " in in_text or " " + punct in in_text) or (COMMA_STRIP.search(in_text) is not None):
            out_text = out_text.replace(punct, "")
        else:
            out_text = out_text.replace(punct, " ")
    out_text = PERIOD_STRIP.sub("", out_text)
    return out_text


def process_digit_article(in_text: str) -> str:
    out_words: list[str] = []
    for word in in_text.lower().split():
        word = MANUAL_MAP.get(word, word)
        if word not in ARTICLES:
            out_words.append(word)
    for index, word in enumerate(out_words):
        if word in CONTRACTIONS:
            out_words[index] = CONTRACTIONS[word]
    return " ".join(out_words)


def normalize_vqa_answer(answer: str) -> str:
    """Normalize one answer string the way VQA v2 scoring does."""
    text = "" if answer is None else str(answer)
    text = text.replace("\n", " ").replace("\t", " ").strip()
    text = process_punctuation(text)
    text = process_digit_article(text)
    return text


def clean_generation(text: str) -> str:
    """Drop thinking traces and chat special tokens before normalization."""
    cleaned = "" if text is None else str(text)
    cleaned = _THINK_RE.sub(" ", cleaned)
    for token in ("<|im_end|>", "<|im_start|>", "<|endoftext|>", "</s>"):
        cleaned = cleaned.replace(token, " ")
    return cleaned.strip()


def normalize_prediction(text: str) -> str:
    return normalize_vqa_answer(clean_generation(text))
